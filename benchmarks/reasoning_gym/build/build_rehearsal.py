"""Build Reasoning Gym t2 rehearsal datasets.

Input: t2 rehearsal traces from tasks generated by `gen_rehearsal.py`, plus
`miniswe-only` and `goose-only` from `build_pools.py`.

Writes:
- `miniswe+goose`: cross-task control.
- `miniswe+goose+reh-t2`: control plus rehearsal rows.
- `reh-t2`: up to 120 solved rehearsal trajectories.
"""
import random
import sys
from glob import glob
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

CAP = 120  # the size of t2-only


def solved(job_dir):
    """Rehearsal trajectories with reward 1, at most two per task, in listing order (as run)."""
    rows, per_task = [], {}
    for t in glob(f"{job_dir}/*/"):
        try:
            if float(open(f"{t}/verifier/reward.txt").read().strip()) < 0.999:
                continue
        except (OSError, ValueError):
            continue
        task = C.task_of(t)
        if per_task.get(task, 0) >= C.PER_TASK:
            continue
        msgs = C.chat_t2(t.rstrip("/"))
        if not msgs:
            continue
        rows.append({"messages": msgs, "meta": {"task": task, "harness": "rgt2-drill", "reward": 1.0}})
        per_task[task] = per_task.get(task, 0) + 1
    return rows


def main():
    p = C.parser(__doc__, {"rehearsal": "rehearsal-t2"})
    args = p.parse_args()
    jobs = C.job_dirs(args, {"rehearsal": "rehearsal-t2"})
    rows = solved(jobs["rehearsal"])
    rate = C.think_rate(rows)
    print(f"rehearsal: {len(rows)} rows from {jobs['rehearsal']} (think rate {rate:.2f})")
    if len(rows) < 40 or rate < 0.9:
        raise SystemExit("fewer than 40 rehearsal rows or think rate below 0.9; check the traces")

    rng = random.Random(0)
    rehearsal = C.capped(rng, rows, CAP)
    cross = C.read_pool(args.out_dir, "miniswe-only") + C.read_pool(args.out_dir, "goose-only")
    for name, rows_ in [("miniswe+goose", cross), ("miniswe+goose+reh-t2", cross + rehearsal), ("reh-t2", rehearsal)]:
        rows_ = rows_[:]
        rng.shuffle(rows_)
        C.write_pool(args.out_dir, name, rows_)


if __name__ == "__main__":
    main()
