"""Build MedAgentBench t2 rehearsal datasets.

Input: t2 rehearsal traces from tasks generated by `gen_rehearsal.py`, plus
`parity-only` and `fc-only` from `build_pools.py`.

Writes:
- `reh-t2`: up to 107 solved rehearsal trajectories.
- `parity+fc+reh-t2`: parity, fc, and rehearsal rows.
- `parity+fc`: cross-task control.
- `reh-t2-fail`: up to 107 failed rehearsal trajectories.

With `--demonstrator 32b`, uses the 32B teacher's rehearsal traces and writes
only `parity+fc+reh-t2-32b`.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

CAP = 107  # the size of t2-only, so rehearsal replaces t2 demonstrations one for one


def parity_fc(out_dir):
    return C.read_pool(out_dir, "parity-only") + C.read_pool(out_dir, "fc-only")


def solved_rehearsal(job_dir, harness, keep_trial):
    rows = C.collect(job_dir, C.chat_t2, {"harness": harness, "reward": 1.0}, keep_trial=keep_trial)
    rate = C.think_rate(rows)
    print(f"rehearsal: {len(rows)} rows from {job_dir} (think rate {rate:.2f})")
    if not rows or rate < 0.9:
        raise SystemExit("empty rehearsal pool or think rate below 0.9; check the traces")
    return rows


def main():
    p = C.parser(__doc__, {"rehearsal": "rehearsal-t2", "rehearsal_32b": "rehearsal-t2-32b"})
    p.add_argument("--demonstrator", choices=["student", "32b"], default="student")
    args = p.parse_args()
    out = args.out_dir

    if args.demonstrator == "32b":
        jobs = C.job_dirs(args, {"rehearsal_32b": "rehearsal-t2-32b"})
        rows = solved_rehearsal(jobs["rehearsal_32b"], "t2-drill32", keep_trial=False)
        if len(rows) < 50:
            raise SystemExit("fewer than 50 rehearsal rows from the 32B teacher")
        rng = random.Random(0)
        pool = parity_fc(out) + C.capped(rng, rows, CAP)
        rng.shuffle(pool)
        C.write_pool(out, "parity+fc+reh-t2-32b", pool)
        return

    jobs = C.job_dirs(args, {"rehearsal": "rehearsal-t2"})

    # rehearsal pools (one seeded stream, as in the original run)
    rng = random.Random(0)
    rehearsal = C.capped(rng, solved_rehearsal(jobs["rehearsal"], "t2-drill", keep_trial=True), CAP)
    C.write_pool(out, "reh-t2", rehearsal)
    pool = parity_fc(out) + rehearsal
    rng.shuffle(pool)
    C.write_pool(out, "parity+fc+reh-t2", pool)

    # controls (a second seeded stream, as in the original run)
    rng = random.Random(0)
    pfc = parity_fc(out)
    control = pfc[:]
    rng.shuffle(control)
    C.write_pool(out, "parity+fc", control)
    # The original run drew two rehearsal-dose pools here (pfc + 25 / + 50 rehearsal rows;
    # not reported). Drawing them keeps the random stream, so reh-t2-fail matches.
    d25 = rng.sample(rehearsal, 25)
    d50 = d25 + rng.sample([r for r in rehearsal if r not in d25], 25)
    rng.shuffle(pfc + d25)
    rng.shuffle(pfc + d50)
    failed = C.collect(jobs["rehearsal"], C.chat_t2, {"harness": "t2-drillfail", "reward": 0.0},
                       reward="0", keep_trial=False, limit=CAP)
    rng.shuffle(failed)
    C.write_pool(out, "reh-t2-fail", failed)


if __name__ == "__main__":
    main()
