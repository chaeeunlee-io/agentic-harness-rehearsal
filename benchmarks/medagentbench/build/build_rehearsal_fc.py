"""Build MedAgentBench fc rehearsal datasets.

Input: fc rehearsal traces from tasks generated by `gen_rehearsal.py --harness fc`,
plus `parity-only` and `t2-only` from `build_pools.py`.

Writes:
- `reh-fc`: up to 150 solved rehearsal trajectories.
- `parity+t2`: cross-task control.
- `parity+t2+reh-fc`: parity, t2, and rehearsal rows.

With `--demonstrator gemma`, uses Gemma rehearsal traces and writes
`reh-fc-gemma` and `parity+t2+reh-fc-gemma`.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

CAP = 150  # the size of fc-only, so rehearsal replaces fc demonstrations one for one


def main():
    p = C.parser(__doc__, {"rehearsal": "rehearsal-fc", "rehearsal_gemma": "rehearsal-fc-gemma"})
    p.add_argument("--demonstrator", choices=["student", "gemma"], default="student")
    args = p.parse_args()
    out = args.out_dir
    gemma = args.demonstrator == "gemma"
    role = "rehearsal_gemma" if gemma else "rehearsal"
    jobs = C.job_dirs(args, {role: "rehearsal-fc-gemma" if gemma else "rehearsal-fc"})

    extract = (lambda t: C.chat_fc(t, inline_think=False)) if gemma else C.chat_fc
    rows = C.collect(jobs[role], extract, {"harness": "fc-drill-gemma" if gemma else "fc-drill", "reward": 1.0})
    print(f"rehearsal: {len(rows)} rows from {jobs[role]}")
    if not rows:
        raise SystemExit("empty rehearsal pool; check the traces")

    rng = random.Random(0)
    rehearsal = C.capped(rng, rows, CAP)
    cross = C.read_pool(out, "parity-only") + C.read_pool(out, "t2-only")
    if gemma:
        C.write_pool(out, "reh-fc-gemma", rehearsal)
        random.Random(0).shuffle(cross)
        pool = cross + rehearsal
        rng.shuffle(pool)
        C.write_pool(out, "parity+t2+reh-fc-gemma", pool)
    else:
        C.write_pool(out, "reh-fc", rehearsal)
        rng.shuffle(cross)
        C.write_pool(out, "parity+t2", cross)
        pool = cross + rehearsal
        rng.shuffle(pool)
        C.write_pool(out, "parity+t2+reh-fc", pool)


if __name__ == "__main__":
    main()
